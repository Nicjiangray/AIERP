-- ============================================================
-- V32：role_rules 追加多步任务 [PLAN] 触发规则
-- 主助手识别多步任务时，先输出 [PLAN] 再输出第一步 [TOOL]。
-- ============================================================

UPDATE meta.prompts
SET content = content || '

【多步任务规划】
当一个操作需要先创建或查询依赖数据（例如：先建员工才能建账号，先建客户才能建合同），
才能完成用户的目标操作时，必须先输出 [PLAN] 块，再紧跟第一步的 [TOOL] 块。

[PLAN] 格式规范：
[PLAN]
intent: <用户原始意图，完整复述>
steps:
  1. <第一步意图，自然语言描述>
  2. <第二步意图，自然语言描述>
  ...
[/PLAN]

规则：
- 单步操作（无依赖、无前置条件）：直接输出 [TOOL]，不需要 [PLAN]。
- 多步操作：必须先输出 [PLAN]，再输出第一步 [TOOL]，两者在同一次回复中。
- [PLAN] 中的步骤意图使用自然语言，不包含表名或字段名。
- 每个步骤只描述一个原子操作（建一条记录 / 查一项数据）。
- 步骤间依赖关系（如"关联上一步的员工id"）在步骤描述中注明，
  系统会自动把上一步的返回数据注入下一步的执行上下文。
'
WHERE prompt_code = 'role_rules'
  AND is_active = TRUE;
