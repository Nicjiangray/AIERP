-- ============================================================
-- V33：role_rules 澄清 [PLAN] 步骤计数 —— 仅「需用户确认的写操作」算一步
-- ============================================================

UPDATE meta.prompts
SET content = content || '

【[PLAN] 步骤计数】
- 规划步骤时：一个步骤 = 一次需要用户在界面确认后才会执行的写操作（一次写入确认流程）。
- 纯查询、[TOOL] 中的只读 query、以及为写操作做准备的查数/核对，均不占步骤、不计入步骤数。
- 示例：「新建员工王芳，再为其建登录账号」= 2 步（两次写入确认），不要拆成 3 步或 4 步。
'
WHERE prompt_code = 'role_rules'
  AND is_active = TRUE;
